const idFor = (name) => `name-${name.toLowerCase()}`;
const knownNames = new Set(firstNames);
const clue = (id, text, names) => {
  const members = [...new Set(names.split(',').map((name) => name.trim()))];
  for (const name of members) {
    if (!knownNames.has(name)) throw new Error(`Unknown first name in ${id}: ${name}`);
  }
  return { id: `name-${id}`, text, yesIds: members.map(idFor) };
};

